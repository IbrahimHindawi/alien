"""Write engine-rasm/simulation/compact_lut.rasm: the AVX2 compress table.

For every 8-bit lane mask m, eight u32 lane indices for vpermps: the set lanes
of m in ascending order first, then zeros. Gathering a block of 8 through
entry m packs its surviving lanes to the front, in order.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rows = []
for m in range(256):
    idx = [i for i in range(8) if m >> i & 1]
    idx += [0] * (8 - len(idx))
    rows.append('    ' + ', '.join(str(i) for i in idx) + ',')
out = ['; simulation/compact_lut.rasm: generated by tools/make_compact_lut.py, do not edit.',
       '; Entry m (32 bytes): the set lanes of the mask m ascending, then zeros.',
       'k_compact_lut: [2048]const u32[align(32)] = {', *rows, '}', '']
(ROOT / 'engine-rasm/simulation/compact_lut.rasm').write_text('\n'.join(out), encoding='utf-8')
